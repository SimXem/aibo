#!/usr/bin/env python3
"""The acceleration sets (2026-11-18): two prompts, asked independently.

data/acceleration_conditions.json (experiments/acceleration.toml,
code/run_unified.py): one joint call asks the headline question,
catastrophe:ai, at every horizon under the unconditional and 12 conditions:
S, software-only self-sustaining acceleration holding without a break for at
least MIN_DURATION over a period between today and the date; F, acceleration
with economic feedback holding so, with software-only acceleration not
holding at any point within that period or before it (it may hold after);
and neither -- each by each of DATES_X.

data/acceleration_elicit.json (experiments/acceleration-elicit.toml,
code/run_elicit.py): a separate call forecasts P(S) and P(F) by each date,
in the same words, and nothing else. Neither call sees the other.

S and F can both hold by one date (F, then S after F's period), so they do
not partition the outcomes: P(cat) = P(cat|S)P(S) + P(cat|F)P(F) +
P(cat|neither)P(neither) - P(cat|S and F)P(S and F), and the last term is
asked by neither prompt.

The definitions are the two agreed on 2026-11-18 (Cunningham et al., "The
Economics of Recursive Self-Improvement", July 2026), verbatim. The question
is the published one: the set names it (`question_ids`) and the runner reads
its text and criteria from the batch (run_unified.set_questions).

    python3 code/make_acceleration_conditions.py           # write both sets
    python3 code/make_acceleration_conditions.py --check   # are they current?
"""
import argparse
import json
import os
import sys
from datetime import date

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(ROOT, "data", "acceleration_conditions.json")
OUT_ELICIT = os.path.join(ROOT, "data", "acceleration_elicit.json")

DATES_X = [date(2027, 12, 31), date(2028, 12, 31), date(2030, 12, 31), date(2040, 12, 31)]
MIN_DURATION = "6 months"
QUESTIONS = ["catastrophe:ai"]
FRAMEWORK = 'Cunningham et al., "The Economics of Recursive Self-Improvement" (July 2026)'

SW_DEF = """Software-only self-sustaining acceleration. Hold fixed the number of human researchers, all compute (for training, experiments and AI inference used in research) and data. The condition holds if, even so, a 1% rise in algorithmic efficiency raises the rate of new algorithmic improvements by more than 1%. This counts both the direct effect of existing ideas on finding new ones and the indirect effect of better AI models doing research.
Formally: ε(Ȧ,A) + ε(Ȧ,C)·ε(C,A) > 1, where C is AI capability, Ȧ is algorithmic improvements and A is algorithmic efficiency."""

EC_DEF = """Self-sustaining acceleration with economic feedback. Hold fixed only the number of human researchers. Compute and data may grow, but only to the extent that resources generated by AI capability gains pay for that growth. Those resources are revenue from better models, or financing that responds to capability progress. Each such input is assumed to grow in proportion to those resources. The condition holds if this whole system accelerates: the growth rates of algorithmic efficiency and of these capability-funded inputs rise as their levels rise. Growth in compute that would have happened anyway does not count.
Formally: the dominant eigenvalue of the matrix of elasticities of each stock's growth with respect to each stock (algorithmic efficiency, training compute, experimental compute, research-inference compute, data) exceeds 1."""

ONE_OFF = ("A one-off jump in compute, from hype, new funding or anything else, does not satisfy either "
           "condition. The conditions concern how strongly progress feeds back into itself, not how fast it moves.")


def long(d):
    return f"{d.strftime('%B')} {d.day}, {d.year}"


def field(d):
    return f"by_{d.year}"


HELD = f"holds without a break for at least {MIN_DURATION}, over a period that lies entirely between today and"
NO_SW = (f"there is no period of at least {MIN_DURATION} between today and {{d}} over which software-only "
         "self-sustaining acceleration holds without a break")
# F's exclusion (2026-11-18): no software-only acceleration at any point
# before or during the economic-feedback period; after it is left open.
# The same words in the elicitation and in the catastrophe conditions.
NOT_BEFORE = ("software-only self-sustaining acceleration does not hold at any point within that period "
              "or before it")
# Both prompts' definitions, the same words in each.
DEFINITIONS = (f"Definitions. These follow the framework in {FRAMEWORK}.\n"
               "Algorithmic efficiency: the inverse of the training compute needed to reach a given level of AI "
               "capability. Self-sustaining acceleration: its growth becomes self-accelerating -- as algorithmic "
               f"efficiency rises, its growth rate also rises.\n\n{SW_DEF}\n\n{EC_DEF}\n\n{ONE_OFF}")
SOURCE = {"wave": f"self-sustaining acceleration ({FRAMEWORK}), min duration {MIN_DURATION}", "panel": "none"}


def elicits():
    fields = [field(d) for d in DATES_X]
    listed = ", ".join(f"{field(d)} ({long(d)})" for d in DATES_X)
    names = ", ".join(fields)
    held, no_sw = HELD, NO_SW
    return [
        {"key": "p_software_only", "fields": fields, "minimum": 0, "maximum": 1,
         "dates": {field(d): d.isoformat() for d in DATES_X},
         "text": (f"Forecast, for each date below, the probability that software-only self-sustaining "
                  f"acceleration actually {held} that date. Forecast the true state, not whether anyone "
                  f"announces it. The dates: {listed}. Give the four probabilities as p_software_only "
                  f"({names}; each in [0,1], non-decreasing, since a later date only adds time).")},
        {"key": "p_with_economic_feedback", "fields": fields, "minimum": 0, "maximum": 1,
         "dates": {field(d): d.isoformat() for d in DATES_X},
         "text": (f"For the same four dates, forecast the probability that self-sustaining acceleration with "
                  f"economic feedback {held} that date, and that {NOT_BEFORE}. Give the four probabilities as "
                  f"p_with_economic_feedback ({names}; each in [0,1], non-decreasing, since a later date only "
                  f"adds time).")},
    ]


def build_elicit():
    """The elicitation set: the definitions and the two quantities, no conditions."""
    return {
        "title": ("Self-sustaining acceleration -- the probability of software-only acceleration, and of "
                  "acceleration with economic feedback with no software-only acceleration before or during it, "
                  "by four dates"),
        "slug": "acceleration-elicit",
        "kind": "elicit",
        "protocol": "elicit-acceleration-v1",
        "generated_by": "code/make_acceleration_conditions.py",
        "source": SOURCE,
        "conditioning": {"definitions": DEFINITIONS},
        "elicits": elicits(),
        "conditions": [],
        "notes": {
            "design": ("2026-11-18: asked alone (code/run_elicit.py), independent of the catastrophe call "
                       "(data/acceleration_conditions.json), whose econ_* conditions are p_with_economic_feedback's "
                       "event in the same words. Both quantities are non-decreasing in the date."),
        },
    }


def build():
    held, no_sw = HELD, NO_SW
    conditions = []
    for kind in ("software", "economic", "none"):
        for d in DATES_X:
            y, dl = d.year, long(d)
            if kind == "software":
                c = {"id": f"sw_{y}", "label": f"Software-only self-sustaining acceleration by {dl}",
                     "assume": f"Assume that software-only self-sustaining acceleration {held} {dl}."}
            elif kind == "economic":
                c = {"id": f"econ_{y}",
                     "label": (f"Self-sustaining acceleration with economic feedback, with no software-only "
                               f"acceleration before or during it, by {dl}"),
                     "assume": (f"Assume that self-sustaining acceleration with economic feedback {held} {dl}, "
                                f"and that {NOT_BEFORE}.")}
            else:
                c = {"id": f"none_{y}", "label": f"Neither by {dl}",
                     "assume": (f"Assume that neither holds by {dl}: {no_sw.format(d=dl)}; and there is no period "
                                f"of at least {MIN_DURATION} between today and {dl} over which self-sustaining "
                                f"acceleration with economic feedback holds without a break while software-only "
                                f"self-sustaining acceleration has not held at any point within or before it.")}
            conditions.append({**c, "group": kind, "date_x": d.isoformat(), "min_duration": MIN_DURATION})

    years = ", ".join(str(d.year) for d in DATES_X[:-1]) + f" or {DATES_X[-1].year}"
    horizon = f"each condition's period ends no later than its date: December 31 of {years}."
    source = SOURCE
    return {
        "title": ("Self-sustaining acceleration conditions -- software-only, economic feedback with no "
                  "software-only before or during it, and neither, each by four dates"),
        "slug": "acceleration",
        "kind": "acceleration",
        "protocol": "unified-joint-acceleration-v1",
        "generated_by": "code/make_acceleration_conditions.py",
        "source": source,
        "question_ids": QUESTIONS,
        "conditioning": {
            "definitions": DEFINITIONS,
            "instruction": (
                "Every condition stands alone: each names one kind of acceleration and one date, and is not "
                "combined with any other condition. Treat each condition as a fact about the world -- whether or "
                "not anyone has measured or announced it -- and not as an intervention: update your expectations "
                "about everything that would ordinarily accompany it -- investment, compute, the pace of AI "
                "capability progress, deployment, and how governments and developers respond -- and then forecast "
                "each question in that world. Do not hold other factors fixed where the condition would change "
                "them. The definitions hold some inputs fixed only to say what each condition is; they do not "
                "assume that those inputs stay fixed in the world you forecast. No policy condition applies: as "
                "in the unconditional forecast, assume whatever AI policies you expect to be implemented."),
            "unconditional_forecast": ("forecast the world as you expect it to unfold, including whatever "
                                       "AI progress, and whatever self-sustaining acceleration, you expect."),
        },
        "groups": [
            {"key": "software", "kind": "software-only", "heading": "SOFTWARE-ONLY ACCELERATION CONDITIONS",
             "instruction": ("For each condition below, assume that software-only self-sustaining acceleration "
                             f"holds without a break for at least {MIN_DURATION}, over a period that lies "
                             "entirely between today and the condition's date."),
             "assumption": ("These conditions assume nothing about self-sustaining acceleration with economic "
                            "feedback beyond what software-only acceleration implies."),
             "horizon": horizon, "source": source},
            {"key": "economic", "kind": "economic-feedback", "heading": "ECONOMIC-FEEDBACK ACCELERATION CONDITIONS",
             "instruction": ("For each condition below, assume that self-sustaining acceleration with economic "
                             f"feedback holds without a break for at least {MIN_DURATION}, over a period that "
                             "lies entirely between today and the condition's date."),
             "assumption": (f"In every condition in this section, {NOT_BEFORE}. Whether it holds after that "
                            "period is left open."),
             "horizon": horizon, "source": source},
            {"key": "none", "kind": "no-acceleration", "heading": "NO-ACCELERATION CONDITIONS",
             "instruction": ("For each condition below, assume that by the condition's date neither holds: no "
                             "condition in the software-only section and no condition in the economic-feedback "
                             "section."),
             "assumption": ("AI progress may still be fast in these conditions, and either kind of acceleration may "
                            "hold for shorter spells; only the two conditions above, as stated, are ruled out."),
             "horizon": horizon, "source": source},
        ],
        "conditions": conditions,
        "notes": {
            "design": ("2026-11-18: P(cat | S), P(cat | F) and P(cat | neither) at each date; the separate "
                       "elicitation call (data/acceleration_elicit.json) asks P(S) and P(F) in the same words. "
                       "S and F can both hold (F, then S after F's period), so the three do not partition the "
                       "outcomes."),
            "today": ("Periods run from 'today', the prompt's first line, so the set is the same file on every "
                      "run date."),
        },
    }


def render(s):
    return json.dumps(s, indent=1, ensure_ascii=False) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description="Write the acceleration scenario set.")
    ap.add_argument("--check", action="store_true", help="fail unless the file is current; write nothing")
    args = ap.parse_args(argv)
    for path, s in ((OUT, build()), (OUT_ELICIT, build_elicit())):
        want, name = render(s), os.path.relpath(path, ROOT)
        if args.check:
            have = open(path).read() if os.path.exists(path) else None
            if have != want:
                sys.exit(f"{name} is stale: run code/make_acceleration_conditions.py")
            print(f"{name} is current")
            continue
        with open(path, "w") as f:
            f.write(want)
        print(f"wrote {name}: {len(s['conditions'])} conditions, {len(s.get('elicits') or [])} elicited quantities")


if __name__ == "__main__":
    main()
